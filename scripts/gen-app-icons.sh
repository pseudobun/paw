#!/usr/bin/env bash
# Embeds sketchybar's app icon map (helpers/app_icons.lua, sketchybar-app-font) into paw as the
# fallback for machines without sketchybar. At runtime paw prefers the live file (icons.map).
# Usage: scripts/gen-app-icons.sh [path/to/app_icons.lua]
set -euo pipefail
cd "$(dirname "$0")/.."
src="${1:-}"
if [ -z "$src" ]; then
  for c in "$HOME/.config/sketchybar/helpers/app_icons.lua" "$HOME/repos/dotfiles/sketchybar/helpers/app_icons.lua"; do
    [ -f "$c" ] && { src="$c"; break; }
  done
fi
[ -n "$src" ] && [ -f "$src" ] || { echo "no app_icons.lua found; pass its path" >&2; exit 1; }
grep -q '"""#' "$src" && { echo "map contains \"\"\"# and cannot be embedded" >&2; exit 1; }
out=Sources/PawCore/BundledAppIcons.swift
{
  echo "// Generated by scripts/gen-app-icons.sh from sketchybar's helpers/app_icons.lua. Do not edit by hand."
  echo "enum BundledAppIcons {"
  echo "    static let lua = #\"\"\""
  cat "$src"
  echo "\"\"\"#"
  echo "}"
} > "$out"
echo "wrote $out ($(grep -c '\] = ' "$src") apps) from $src"
